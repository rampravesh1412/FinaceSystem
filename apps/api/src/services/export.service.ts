import ExcelJS from "exceljs";
import PDFDocument from "pdfkit";
import { formatINR, paiseToRupees } from "@amiri/shared";
import { env } from "../config/env.js";

/**
 * Report export (§53, §54).
 *
 * One description of a report, three renderings. A report is described once as columns and
 * rows, then written as CSV, Excel or PDF — so a figure cannot appear one way on screen
 * and another in the file somebody emails to their accountant.
 *
 * Every format carries the same provenance block, which is what §53 and §54 are really
 * asking for: an exported figure is worthless if nobody can tell what it covered, who
 * produced it and when. A spreadsheet of numbers with no date range is a liability.
 */

export type ColumnAlign = "left" | "right" | "center";

export interface ExportColumn<T> {
  key: string;
  header: string;
  /** `money` values are integer paise and are rendered per format. */
  type?: "text" | "money" | "date" | "number";
  align?: ColumnAlign;
  width?: number;
  value: (row: T) => string | number | null | undefined;
  /** Include this column in the totals row. */
  total?: boolean;
}

export interface ExportSpec<T> {
  /** File name without extension. */
  filename: string;
  title: string;
  subtitle?: string;
  columns: Array<ExportColumn<T>>;
  rows: T[];

  /** The provenance block — §54's header requirements. */
  meta: {
    organisation: string;
    branch?: string;
    from?: Date;
    to?: Date;
    asOf?: Date;
    generatedBy: string;
    filters?: Record<string, string | undefined>;
  };

  /** Extra summary lines beneath the table: net profit, difference, tally status. */
  summary?: Array<{ label: string; value: string; emphasis?: boolean }>;
}

export type ExportFormat = "csv" | "xlsx" | "pdf";

/* -------------------------------------------------------------------------- */
/* Shared helpers                                                             */
/* -------------------------------------------------------------------------- */

function formatDate(date: Date | undefined): string {
  if (!date) return "";
  return date.toLocaleDateString("en-IN", { day: "2-digit", month: "short", year: "numeric" });
}

/** The provenance lines, identical across all three formats. */
function metaLines(meta: ExportSpec<unknown>["meta"]): Array<[string, string]> {
  const lines: Array<[string, string]> = [];

  if (meta.branch) lines.push(["Branch", meta.branch]);
  if (meta.from && meta.to) {
    lines.push(["Period", `${formatDate(meta.from)} to ${formatDate(meta.to)}`]);
  } else if (meta.asOf) {
    lines.push(["As at", formatDate(meta.asOf)]);
  }

  for (const [key, value] of Object.entries(meta.filters ?? {})) {
    if (value) lines.push([key, value]);
  }

  lines.push(["Generated by", meta.generatedBy]);
  lines.push(["Generated at", new Date().toLocaleString("en-IN")]);

  return lines;
}

function cellValue<T>(column: ExportColumn<T>, row: T): string | number | null {
  const raw = column.value(row);
  if (raw === null || raw === undefined) return null;

  if (column.type === "money") {
    // Exported as RUPEES, not paise. A spreadsheet column of 12510100 that means
    // ₹1,25,101 is a trap — someone will sum it and be out by a factor of a hundred.
    return paiseToRupees(Number(raw));
  }
  return raw;
}

function totalsFor<T>(spec: ExportSpec<T>): Map<string, number> {
  const totals = new Map<string, number>();
  for (const column of spec.columns) {
    if (!column.total) continue;
    let sum = 0;
    for (const row of spec.rows) sum += Number(column.value(row) ?? 0);
    totals.set(column.key, column.type === "money" ? paiseToRupees(sum) : sum);
  }
  return totals;
}

