async function renderXlsx<T>(spec: ExportSpec<T>): Promise<Buffer> {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = spec.meta.organisation;
  workbook.created = new Date();

  const sheet = workbook.addWorksheet(spec.title.slice(0, 30), {
    // Repeat the header row on every printed page.
    views: [{ state: "frozen", ySplit: 0 }],
  });

  const titleRow = sheet.addRow([spec.meta.organisation]);
  titleRow.font = { bold: true, size: 14 };
  sheet.addRow([spec.title]).font = { bold: true, size: 12 };
  if (spec.subtitle) sheet.addRow([spec.subtitle]).font = { italic: true, size: 10 };

  for (const [label, value] of metaLines(spec.meta)) {
    const row = sheet.addRow([label, value]);
    row.font = { size: 9, color: { argb: "FF666666" } };
  }
  sheet.addRow([]);

  const headerRowIndex = sheet.rowCount + 1;
  const header = sheet.addRow(spec.columns.map((c) => c.header));
  header.font = { bold: true, color: { argb: "FFFFFFFF" } };
  header.eachCell((cell) => {
    cell.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FF1E293B" } };
    cell.alignment = { vertical: "middle" };
  });

  for (const row of spec.rows) {
    const values = spec.columns.map((c) => cellValue(c, row));
    const added = sheet.addRow(values);

    spec.columns.forEach((column, i) => {
      const cell = added.getCell(i + 1);
      if (column.type === "money") {
        // A real Excel number with Indian grouping — the recipient can sum the column,
        // which is the entire reason for exporting to a spreadsheet rather than a PDF.
        cell.numFmt = '##,##,##0.00;[Red]-##,##,##0.00';
        cell.alignment = { horizontal: "right" };
      } else if (column.align) {
        cell.alignment = { horizontal: column.align };
      }
    });
  }

  const totals = totalsFor(spec);
  if (totals.size > 0) {
    const totalRow = sheet.addRow(
      spec.columns.map((c, i) => (i === 0 ? "TOTAL" : (totals.get(c.key) ?? null))),
    );
    totalRow.font = { bold: true };
    totalRow.eachCell((cell, col) => {
      cell.border = { top: { style: "thin" } };
      if (spec.columns[col - 1]?.type === "money") {
        cell.numFmt = '##,##,##0.00;[Red]-##,##,##0.00';
      }
    });
  }

  if (spec.summary?.length) {
    sheet.addRow([]);
    for (const item of spec.summary) {
      const row = sheet.addRow([item.label, item.value]);
      if (item.emphasis) row.font = { bold: true };
    }
  }

  spec.columns.forEach((column, i) => {
    sheet.getColumn(i + 1).width = column.width ?? Math.max(12, column.header.length + 4);
  });

  sheet.autoFilter = {
    from: { row: headerRowIndex, column: 1 },
    to: { row: headerRowIndex, column: spec.columns.length },
  };

  // ExcelJS declares its own Buffer type from an older @types/node; going through
  // `unknown` avoids a structural mismatch that has nothing to do with the bytes.
  return Buffer.from((await workbook.xlsx.writeBuffer()) as unknown as ArrayBuffer);
}

