/**
 * PDF (§54).
 *
 * Header carries the organisation, report name and range; the footer carries who
 * generated it, when, and a page number. Both repeat on every page, because a page torn
 * out of a report has to remain identifiable.
 *
 * NOTE on the rupee sign: the built-in Helvetica has no ₹ glyph and would render a blank
 * box, so PDF amounts are prefixed "Rs." instead. Shipping a font file just for one glyph
 * is not worth the weight, and a blank box where a currency symbol should be is worse
 * than an unambiguous abbreviation.
 */
function renderPdf<T>(spec: ExportSpec<T>, res: Response): void {
  const doc = new PDFDocument({ size: "A4", layout: "landscape", margin: 36 });
  doc.pipe(res);

  const pageWidth = doc.page.width - 72;
  const totals = totalsFor(spec);

  const widths = spec.columns.map((c) => c.width ?? 100);
  const widthSum = widths.reduce((a, b) => a + b, 0);
  const scaled = widths.map((w) => (w / widthSum) * pageWidth);

  const money = (value: number): string => `Rs. ${formatINR(value, { symbol: false })}`;

  const drawHeader = (): void => {
    doc.fontSize(14).font("Helvetica-Bold").text(spec.meta.organisation, 36, 30);
    doc.fontSize(11).font("Helvetica-Bold").text(spec.title, 36, 48);
    if (spec.subtitle) doc.fontSize(9).font("Helvetica").text(spec.subtitle, 36, 64);

    let y = spec.subtitle ? 78 : 64;
    doc.fontSize(8).font("Helvetica").fillColor("#555555");
    for (const [label, value] of metaLines(spec.meta)) {
      doc.text(`${label}: ${value}`, 36, y);
      y += 10;
    }
    doc.fillColor("#000000");

    doc.moveTo(36, y + 4).lineTo(doc.page.width - 36, y + 4).strokeColor("#cccccc").stroke();
    doc.y = y + 12;
  };

  const drawColumnHeaders = (): void => {
    const y = doc.y;
    doc.rect(36, y - 2, pageWidth, 16).fill("#1e293b");
    doc.fillColor("#ffffff").fontSize(8).font("Helvetica-Bold");

    let x = 36;
    spec.columns.forEach((column, i) => {
      doc.text(column.header, x + 3, y + 2, {
        width: scaled[i]! - 6,
        align: column.align ?? (column.type === "money" ? "right" : "left"),
        lineBreak: false,
      });
      x += scaled[i]!;
    });

    doc.fillColor("#000000");
    doc.y = y + 18;
  };

  const drawRow = (row: T, striped: boolean): void => {
    const y = doc.y;
    if (y > doc.page.height - 60) {
      doc.addPage();
      drawHeader();
      drawColumnHeaders();
    }

    const top = doc.y;
    if (striped) doc.rect(36, top - 1, pageWidth, 14).fill("#f5f5f4").fillColor("#000000");

    doc.fontSize(8).font("Helvetica");
    let x = 36;
    spec.columns.forEach((column, i) => {
      const raw = column.value(row);
      const text =
        column.type === "money" && raw !== null && raw !== undefined
          ? money(Number(raw))
          : raw === null || raw === undefined
            ? ""
            : String(raw);

      doc.text(text, x + 3, top + 2, {
        width: scaled[i]! - 6,
        align: column.align ?? (column.type === "money" ? "right" : "left"),
        lineBreak: false,
        ellipsis: true,
      });
      x += scaled[i]!;
    });

    doc.y = top + 14;
  };

  drawHeader();
  drawColumnHeaders();
  spec.rows.forEach((row, i) => drawRow(row, i % 2 === 1));

  if (totals.size > 0) {
    const top = doc.y + 2;
    doc.moveTo(36, top).lineTo(doc.page.width - 36, top).strokeColor("#333333").stroke();
    doc.fontSize(8).font("Helvetica-Bold");

    let x = 36;
    spec.columns.forEach((column, i) => {
      const text =
        i === 0
          ? "TOTAL"
          : totals.has(column.key)
            ? column.type === "money"
              ? `Rs. ${formatINR(Math.round(totals.get(column.key)! * 100), { symbol: false })}`
              : String(totals.get(column.key))
            : "";
      doc.text(text, x + 3, top + 4, {
        width: scaled[i]! - 6,
        align: column.align ?? (column.type === "money" ? "right" : "left"),
        lineBreak: false,
      });
      x += scaled[i]!;
    });
    doc.y = top + 18;
  }

  if (spec.summary?.length) {
    doc.moveDown(0.5);
    for (const item of spec.summary) {
      doc.fontSize(9).font(item.emphasis ? "Helvetica-Bold" : "Helvetica");
      doc.text(`${item.label}: ${item.value}`, 36, doc.y);
    }
  }

  // Footer on every page, added after layout so the page count is known.
  const range = doc.bufferedPageRange();
  for (let i = 0; i < range.count; i += 1) {
    doc.switchToPage(range.start + i);
    doc.fontSize(7).font("Helvetica").fillColor("#666666");
    doc.text(
      `${spec.meta.organisation} · ${spec.title} · generated by ${spec.meta.generatedBy} on ${new Date().toLocaleString("en-IN")}`,
      36,
      doc.page.height - 28,
      { width: pageWidth - 60, lineBreak: false },
    );
    doc.text(`Page ${i + 1} of ${range.count}`, doc.page.width - 110, doc.page.height - 28, {
      width: 74,
      align: "right",
      lineBreak: false,
    });
  }

  doc.end();
}

