export async function sendExport<T>(
  res: Response,
  format: ExportFormat,
  spec: ExportSpec<T>,
): Promise<void> {
  const stamp = new Date().toISOString().slice(0, 10);
  const filename = `${spec.filename}-${stamp}`;

  // Quoted and sanitised: an unescaped filename is a header-injection vector, and a
  // report name containing a comma otherwise truncates the header.
  const safe = filename.replace(/[^\w.-]+/g, "_");

  switch (format) {
    case "csv": {
      res.setHeader("content-type", "text/csv; charset=utf-8");
      res.setHeader("content-disposition", `attachment; filename="${safe}.csv"`);
      res.send(renderCsv(spec));
      return;
    }

    case "xlsx": {
      const buffer = await renderXlsx(spec);
      res.setHeader(
        "content-type",
        "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
      );
      res.setHeader("content-disposition", `attachment; filename="${safe}.xlsx"`);
      res.send(buffer);
      return;
    }

    case "pdf": {
      res.setHeader("content-type", "application/pdf");
      res.setHeader("content-disposition", `attachment; filename="${safe}.pdf"`);
      renderPdf(spec, res);
      return;
    }

    default:
      throw new Error(`Unsupported export format: ${String(format)}`);
  }
}

/** The organisation block every export carries. */
/**
 * The provenance block printed on every export (§54).
 *
 * The organisation name comes from the SETTINGS profile, not from `ORG_NAME`. Once the
 * name is editable in the UI, an export that kept printing the env value would put a
 * different name on the file from the one on screen — a discrepancy in precisely the
 * field whose job is to say who produced the document. `ORG_NAME` remains the fallback
 * for a fresh installation that has not been through Settings yet.
 *
 * Async because it reads that profile, cached because an export of 20,000 rows should not
 * pay for a settings lookup it can make once a minute.
 */
export async function exportMeta(options: {
  branch?: string;
  from?: Date;
  to?: Date;
  asOf?: Date;
  generatedBy: string;
  filters?: Record<string, string | undefined>;
}): Promise<ExportSpec<unknown>["meta"]> {
  return { organisation: await organisationName(), ...options };
}

let cachedName: { value: string; at: number } | null = null;
const NAME_TTL_MS = 60_000;

async function organisationName(): Promise<string> {
  if (cachedName && Date.now() - cachedName.at < NAME_TTL_MS) return cachedName.value;

  try {
    const { getProfile } = await import("../modules/settings/settings.service.js");
    const profile = await getProfile();
    cachedName = { value: profile.displayName || profile.legalName, at: Date.now() };
  } catch {
    // A settings read must never be the reason an export fails — the name is a header.
    cachedName = { value: env.ORG_NAME, at: Date.now() };
  }

  return cachedName.value;
}

/** Called when the profile is saved, so the next export shows the new name immediately. */
export function invalidateOrganisationName(): void {
  cachedName = null;
}
