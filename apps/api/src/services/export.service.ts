/**
 * Escape a CSV field.
 *
 * The leading-character guard is a security control, not formatting: a field starting
 * `=`, `+`, `-` or `@` is interpreted as a FORMULA when the file is opened in Excel, and a
 * party named `=cmd|'/c calc'!A1` becomes code execution on the machine of whoever opens
 * the export. Prefixing with a single quote neutralises it while still displaying the
 * original text.
 */
function csvField(value: string | number | null): string {
  if (value === null || value === undefined) return "";
  let text = String(value);

  if (/^[=+\-@\t\r]/.test(text)) text = `'${text}`;
  if (/[",\n\r]/.test(text)) text = `"${text.replace(/"/g, '""')}"`;

  return text;
}

function renderCsv<T>(spec: ExportSpec<T>): string {
  const lines: string[] = [];

  lines.push(csvField(spec.meta.organisation));
  lines.push(csvField(spec.title));
  if (spec.subtitle) lines.push(csvField(spec.subtitle));
  for (const [label, value] of metaLines(spec.meta)) {
    lines.push(`${csvField(label)},${csvField(value)}`);
  }
  lines.push("");

  lines.push(spec.columns.map((c) => csvField(c.header)).join(","));
  for (const row of spec.rows) {
    lines.push(spec.columns.map((c) => csvField(cellValue(c, row))).join(","));
  }

  const totals = totalsFor(spec);
  if (totals.size > 0) {
    lines.push(
      spec.columns
        .map((c, i) => (i === 0 ? csvField("TOTAL") : csvField(totals.get(c.key) ?? "")))
        .join(","),
    );
  }

  if (spec.summary?.length) {
    lines.push("");
    for (const item of spec.summary) lines.push(`${csvField(item.label)},${csvField(item.value)}`);
  }

  // A UTF-8 BOM, so Excel renders ₹ and Devanagari correctly instead of mojibake.
  return `﻿${lines.join("\r\n")}`;
}

