describe("notifications (§50)", () => {
  it("notifies the approvers when a transaction is held", async () => {
    await client.request("PUT", "/approvals/settings", {
      token,
      body: {
        enabled: true,
        minimumAmount: "1,000",
        tiers: [{ from: "0", to: null, tier: "BRANCH_ADMIN" }],
        appliesTo: [],
      },
    });

    const account = await client.get<{ data: Array<{ id: string }> }>("/bank-accounts", { token });
    const party = await Party.findOne({ name: "Sharma Traders" }).lean();

    await client.post(
      "/payment-out",
      {
        date: "2026-08-22", partyId: String(party!._id),
        accountId: account.body.data[0]!.id, amount: "40,000", paymentMode: "NEFT",
      },
      { token },
    );

    // Fan-out happens at send time, one row per user.
    const sent = await Notification.find({ type: "APPROVAL_REQUIRED" }).lean();
    expect(sent.length).toBeGreaterThan(0);
    expect(sent[0]!.title).toMatch(/needs approval/i);
    expect(sent[0]!.link).toBe("/approvals");

    await client.request("PUT", "/approvals/settings", {
      token,
      body: { enabled: false, minimumAmount: "0", tiers: [], appliesTo: [] },
    });
  });

  it("serves only the caller's own notifications", async () => {
    const res = await client.get<{ data: { items: Array<{ title: string }>; unread: number } }>(
      "/notifications",
      { token },
    );

    expect(res.status).toBe(200);
    const mine = await Notification.countDocuments({ userId: fx.users.superAdmin!.id });
    expect(res.body.data.items.length).toBe(Math.min(mine, 30));
  });

  it("marks notifications read", async () => {
    const before = await client.get<{ data: { unread: number } }>("/notifications", { token });
    if (before.body.data.unread === 0) return;

    const res = await client.post<{ data: { marked: number } }>("/notifications/read", {}, { token });
    expect(res.body.data.marked).toBeGreaterThan(0);

    const after = await client.get<{ data: { unread: number } }>("/notifications", { token });
    expect(after.body.data.unread).toBe(0);
  });

  it("does not let a notification failure break the transaction that triggered it", async () => {
    // Notifications are sent AFTER commit and swallow their own errors — a payment must
    // never fail because a courtesy message could not be delivered.
    const { notify } = await import("../notifications/notification.service.js");
    await expect(notify(["not-a-valid-object-id"], { type: "LOW_BALANCE", title: "x" })).resolves.toBeUndefined();
  });
});
